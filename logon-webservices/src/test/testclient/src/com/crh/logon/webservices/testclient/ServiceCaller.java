package com.crh.logon.webservices.testclient;

import java.io.File;
import java.lang.reflect.Constructor;
import java.lang.reflect.InvocationTargetException;
import java.lang.reflect.Method;
import java.math.BigInteger;
import java.util.Collection;
import java.util.Iterator;

import javax.wsdl.Definition;
import javax.wsdl.Operation;
import javax.wsdl.Part;
import javax.wsdl.PortType;
import javax.wsdl.Service;
import javax.wsdl.WSDLException;
import javax.wsdl.factory.WSDLFactory;
import javax.wsdl.xml.WSDLReader;
import javax.xml.parsers.DocumentBuilder;
import javax.xml.parsers.DocumentBuilderFactory;
import javax.xml.parsers.ParserConfigurationException;

import org.apache.commons.beanutils.MethodUtils;
import org.apache.commons.beanutils.PropertyUtils;
import org.apache.commons.lang.StringUtils;
import org.w3c.dom.Document;
import org.w3c.dom.Element;
import org.w3c.dom.Node;
import org.w3c.dom.NodeList;

import com.crh.logon.exception.WsClientSideExceptionHandler;

import ch.nevis.jcan.log.JcanLogger;
import ch.nevis.jcan.log.JcanLoggerFactory;

/** 
 * This class performs the actual call, but first it applies various transformations to 
 * the request files be able to call the axis2 put operation.
 * 
 * Transformations:
 *  1) *.request (full captured SOAP envelope)
 * 		- extract the body part of the message
 * 
 *  2) *.requestbody (autogenerated xml fragment based on the message schema)
 *      - extract the xml fragment from the parsed document
 *      - wrap it into the put_operation + message_part tag
 *      
 * @author AdNovum Informatik AG
 */
final class ServiceCaller implements Comparable<ServiceCaller> {
	
	private static final JcanLogger LOG = JcanLoggerFactory.getLogger(ServiceCaller.class);

	private final static String MEMBER_ENDING_PUT_RESPONSE = "PutResponse";
	private final static String MEMBER_ENDING_FACTORY = "Factory";
	private final static String METHOD_PARSE = "parse";

	private final static String BEAN_STATUS_CODE = ".status.code";
	private final static String BEAN_STATUS_TXT = ".status.txt";

	private final static String WSDL_NS_URI = "http://schemas.xmlsoap.org/soap/envelope/";
	private final static String WSDL_TAG_BODY = "Body";
	private final static String XML_NS_NAME = "ns0";
	private final static String XML_NS_ATTR = "xmlns";
	
	/**
	 * used upon construction to parse the WSDL definition so we will know
	 * various attributes (like the put_operation or msg_part, etc.)
	 */
	private final static WSDLReader WSDLReader;
	
	/**
	 * used for every request file, to make sure that it contains valid xml,
	 * and perform transformation on it (also the axis2 put_operation is called
	 * with a DOM node).
	 */
	private final static DocumentBuilder documentBuilder;
	
	static {
		try {
			WSDLReader = WSDLFactory.newInstance().newWSDLReader();
		} catch (WSDLException e) {
			throw new ExceptionInInitializerError(e);
		}
		
		try {
			final DocumentBuilderFactory factory =  DocumentBuilderFactory.newInstance();
			factory.setNamespaceAware(true);
			factory.setValidating(false);
			factory.setIgnoringComments(false);
			factory.setIgnoringElementContentWhitespace(false);
			
			documentBuilder = factory.newDocumentBuilder();
			
		}
		catch (ParserConfigurationException e) {
			throw new ExceptionInInitializerError(e);
		}
	}

	/**
	 * Inspect the collection, and makes sure that it contains only one item.
	 * 
	 * @param collection collection to inspect
	 * @param name wsdl name
	 * @param errorMsg error message to throw
	 * @return the only item
	 * @throws WSDLException if the collection contains more than 1 item.
	 */
	private static Object assertOnlyOneItem(Collection<?> collection, String name, String errorMsg) throws WSDLException {
		final Iterator<?> iter = collection.iterator();
		final Object ret = iter.next();
		
		if (iter.hasNext()) {
			throw new WSDLException(WSDLException.OTHER_ERROR,
							String.format(
									"Specified wsdl (%s) contains more than one %s!",
									name, errorMsg));
		}
		return ret;
	}

	private final Class<?> documentClass;
	private final Constructor<?> stubConstructor;

	private final String name;
	private final String importName;
	private final Method putMethod;

	private final String operationName;
	private final String inputMsgPartName;
	private final String inputMsgPartTypeName;
	private final String axis2EntityName;
	
	ServiceCaller(String name) throws SecurityException, NoSuchMethodException, ClassNotFoundException, IllegalArgumentException, WSDLException {
		
		final Definition def = WSDLReader.readWSDL("etc/wsdl/" + name + ".wsdl");
		
		final Service service = (Service) assertOnlyOneItem(
								def.getServices().values(), 
								name,
								"service");
											
		@SuppressWarnings("unchecked")
		final Collection <PortType> portTypes = def.getPortTypes().values();
		
		final PortType portType = (PortType) assertOnlyOneItem(
							portTypes, 
							name, 
							"portType");
		 			
		final Operation operation = (Operation) assertOnlyOneItem(
							portType.getOperations(), 
							name, 
							"operation");
			
		final Part inputMsgPart = (Part) assertOnlyOneItem(
						operation.getInput().getMessage().getParts().values(), 
						name, 
						"message parts for the input operation");
		
		this.inputMsgPartName = inputMsgPart.getName();
		this.inputMsgPartTypeName = inputMsgPart.getTypeName().getLocalPart();
		this.axis2EntityName = inputMsgPartTypeName.replaceAll("_", "");
		
		this.name = name;
		this.importName = service.getQName().getLocalPart();			
		this.documentClass = Class.forName(
				String.format(
						"com.crh.logon.webservices.%s.documents.%sPutDocument",
						this.name, 
						axis2EntityName));	
		
		final Class<?> stubClass = Class.forName(
							String.format(
									"com.crh.logon.webservices.%s.client.%sImportStub",
									this.name, 
									axis2EntityName));	
		
		this.stubConstructor = stubClass.getConstructor(String.class);

		this.putMethod = stubClass.getMethod(
									operation.getName(), 
									documentClass);
		this.operationName = putMethod.getName();
		
		if (LOG.isDebugEnabled()) {
			LOG.debug("-----------------");
			LOG.debug("name            = '" + name + "'");
			LOG.debug("importName      = '" + importName + "'");
			LOG.debug("putMethod       = '" + putMethod + "'");
			LOG.debug("documentClass   = '" + documentClass + "'");
			LOG.debug("stubClass       = '" + stubClass + "'");
			LOG.debug("stubConstructor = '" + stubConstructor + "'");
			LOG.debug("-----------------");
		}
	}	
	
	/**
	 * Performs the tests on the service.
	 * 
	 * @param messageNamespace the namespace of the messages itself
	 * @param serviceBaseUrl The base URL of the endpoint.
	 * @param testFiles the files to parse/pass to axis2
	 * @param expectOnlyBody whether the files are full SOAP messages or not.
	 */
	void callTests(String messageNamespace, String serviceBaseUrl, Collection<File> testFiles, boolean expectOnlyBody) {
		final boolean debugEnabled = LOG.isDebugEnabled();
		final boolean infoEnabled = LOG.isInfoEnabled();
		
		if (debugEnabled) {
			Object[][] params = { 
					{ "messageNamespace", messageNamespace},
					{ "serviceBaseUrl", serviceBaseUrl}, 
					{ "testFiles", testFiles},
					{ "expectOnlyBody", expectOnlyBody},
					{ "name", this.name}};
			LOG.entering(this, "callTests", params);
		}
		try {
			if ((testFiles == null) || (testFiles.isEmpty())) {
				if (infoEnabled) {
					LOG.info("There are no testfiles to process, returning!");
				}
				return;
			}
			else {
				if (infoEnabled) {
					LOG.info("**** " + importName.toUpperCase() + " :: START ****");
				}
				
				final String stubFQArg = serviceBaseUrl + importName;
				final Object stub;
				
				try {
					stub = stubConstructor.newInstance(stubFQArg);
				}
				catch (Exception e) {
					LOG.error(String.format(
							"Unable to create stub for %s with argument '%s', skipping service!", 
							importName,
							stubFQArg), e);
					return;
				}

				if (infoEnabled) {
					LOG.info(" connected to webservice at " + stubFQArg + " .");
				}
				
				for (File testFile : testFiles) {
					callTest(messageNamespace, stub, testFile, expectOnlyBody);
				}
				
				if (infoEnabled) {				
					LOG.info("**** " + importName.toUpperCase() + " :: END ****");
				}
			}
		}
		catch (Exception e) {
			WsClientSideExceptionHandler.handle(
					e, 
					importName, 
					importName + "Stub");
		}
		finally {
			if (debugEnabled) {
				LOG.exiting();
			}
		}
	}

	/**
	 * This method performs test one-by-one.
	 * 
	 * @param messageNamespace the namespace of the messages itself
	 * @param stub the axis2 stub to use.
	 * @param testFile the file which contains the message to send.
	 * @param expectOnlyBody whether the files are full SOAP messages or not.
	 */
	private void callTest(String messageNamespace, Object stub, File testFile, boolean expectOnlyBody) {
		final boolean debugEnabled = LOG.isDebugEnabled();
		
		if (debugEnabled) {
			Object[][] params = { 
					{ "messageNamespace", messageNamespace},
					{ "stub", stub},
					{ "testFile", testFile},
					{ "expectOnlyBody", expectOnlyBody},
					{ "name", this.name}};
			LOG.entering(this, "callTest", params);
		}
		try {

			final Document doc = documentBuilder.parse(testFile);
			NodeList elements;
						
			if (expectOnlyBody) {
				elements = doc.getElementsByTagName(this.name);
			}
			else {
				elements = doc.getElementsByTagNameNS(WSDL_NS_URI, WSDL_TAG_BODY);
			}			
			
			if (elements.getLength() != 1) {
				LOG.error(String.format(
						"Request file %s is not well formed (contains %s '%s' tags, instead of exactly one)! Skipping...", 
						testFile.getPath(),
						elements.getLength(),
						expectOnlyBody ? this.name : WSDL_NS_URI + ":" +  WSDL_TAG_BODY));
				
				return;
			}
			
			Node node = elements.item(0);
			elements = node.getChildNodes();
			
			node = null;
			for (int i=0; i < elements.getLength(); i++) {
				node = elements.item(i);
				
				if (node.getNodeType() == Node.ELEMENT_NODE) {
					break;
				}
			}
			
			if (node == null) {
				LOG.error(String.format(
						"Request file %s is not well formed (there is no subelement to call the put method with)! Skipping...", 
						testFile.getPath(),
						elements.getLength(),
						expectOnlyBody ? this.name : WSDL_NS_URI + ":" +  WSDL_TAG_BODY));
				return;
			}
		    
			if (expectOnlyBody) {
				/*
				 * if we have a .requestbody file, which is an autogenerated xml
				 * based on the xsd schema, then we have to wrap it into the operation
				 * and message tag according the wsdl message definition
				 */			
				final Element outer = doc.createElementNS(messageNamespace, operationName);				
				outer.setAttribute(XML_NS_ATTR + ":" + XML_NS_NAME, messageNamespace);
				
				final Element inner = doc.createElement(inputMsgPartName);
				inner.appendChild(node);
				outer.appendChild(inner);
				
				node = outer;
			}
			
			performPutOn(stub, node);
		} 
		catch (Throwable t) {
			WsClientSideExceptionHandler.handle(
					t, 
					importName, 
					importName + "Stub");
		}
		finally {
			if (debugEnabled) {
				LOG.exiting();
			}
		}
	}
	
	/**
	 * This method calls axis2 with the request data, also it parses the response status (if any).
	 * @param stub the axis2 stub to use.
	 * @param requestNode the DOM node containing the request
	 * @throws IllegalAccessException
	 * @throws InvocationTargetException
	 * @throws NoSuchMethodException
	 * @throws ClassNotFoundException
	 */
	private void performPutOn(Object stub, Node requestNode) throws IllegalAccessException, InvocationTargetException, NoSuchMethodException, ClassNotFoundException {
		final boolean debugEnabled = LOG.isDebugEnabled();

		if (debugEnabled) {
			Object[][] params = { 
					{ "stub", stub}, 
					{ "requestNode", requestNode} };
			LOG.entering(this, "performPutOn", params);
		}
		try {
			
			// get the document's factory class
			final Class<?> documentFactoryClass = Class.forName(
								documentClass.getName() + "$" + MEMBER_ENDING_FACTORY);
			
			// get the parser method
			final Method parserMethod = MethodUtils.getAccessibleMethod(
															documentFactoryClass, 
															METHOD_PARSE, 
															Node.class);
			
			// parse
			final Object document = documentClass.cast(
													parserMethod.invoke(
													null, requestNode));

			// invoke request
			final Object responseDocument;
			try {
				responseDocument = putMethod.invoke(stub, document);
			} catch (InvocationTargetException e) {
				LOG.error(String.format(
						"%s in %s FAILED. Check the server-side logs for more information!", 
						operationName, 
						importName),
						e.getTargetException());
				return;
			}
			
			final String responseProperty = StringUtils.uncapitalize(axis2EntityName + MEMBER_ENDING_PUT_RESPONSE);

			/*
			 * from the response get the statuscode as a nested bean property, like:
			 * 
			 */
			final BigInteger statusCode = (BigInteger) PropertyUtils.getProperty(
													responseDocument, 
													responseProperty + BEAN_STATUS_CODE);
																			
			if (statusCode == null) {
				LOG.error(String.format(
						"%s in %s FAILED (no status code). Check the server-side logs for more information!",
						operationName, 
						importName));
			}
			else {
				final String statusTxt = (String) PropertyUtils.getProperty(
													responseDocument, 
													responseProperty + BEAN_STATUS_TXT);
				
				if (BigInteger.ONE.equals(statusCode)) {
					if (LOG.isInfoEnabled()) {
						LOG.info(String.format(
								"\t  Statuscode: %s %s",
								statusCode, 
								statusTxt));					
					}
				}
				else {
					LOG.error(String.format(
							"\t  FAILURE Statuscode: %s %s",
							statusCode, 
							statusTxt));
				}
			}			
		}
		finally {
			if (debugEnabled) {
				LOG.exiting();
			}
		}
	}

	String getName() {
		return name;
	}
	
	String getOperationName() {
		return operationName;
	}
	
	public int compareTo(ServiceCaller o) {
		return this.name.compareTo(o.name);
	}
	
	public String toString() {
		return this.name;
	}
}