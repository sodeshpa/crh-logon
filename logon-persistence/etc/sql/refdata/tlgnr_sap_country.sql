-------------------------------------------------------------------------------
-- is_different_varchar2
-------------------------------------------------------------------------------
-- compares two varchars.
-- They are identical either if a) both are null, b) they are equal by "="
-- They are different if a) either is null and the other not, b) different by "="
create or replace function is_different_varchar2 (
  i_a in varchar2,
  i_b in varchar2)
  return number is
  begin
    if ((i_a != i_b)
        or (i_a is null and i_b is not null)
        or (i_a is not null and i_b is null)) then
      return 1;
    end if;
    return 0;
  end;
/
show errors;

-------------------------------------------------------------------------------
-- is_different_number
-------------------------------------------------------------------------------
-- compares two numbers.
-- They are identical either if a) both are null, b) they are equal by "="
-- They are different if a) either is null and the other not, b) different by "="
create or replace function is_different_number (
    i_a in number,
    i_b in number)
  return number is
begin
  if ((i_a != i_b)
    or (i_a is null and i_b is not null)
    or (i_a is not null and i_b is null)) then
      return 1;
  end if;
  return 0;
end;
/
show errors;

-------------------------------------------------------------------------------
-- tlgnr_sap_country_bs
-------------------------------------------------------------------------------
create or replace
procedure upsert_sap_country_bs (
    p_sap_country_cd          in varchar2,
    p_ctl_act_cd              in number

) is
    v_exists_flag                   number;        -- number of existing records of that key (0 or 1)
    v_ctl_act_cd                    number := p_ctl_act_cd;

begin
  dbms_output.enable(100000);

  dbms_output.put_line('Insert or Update tlgnr_sap_country_bs (' || p_sap_country_cd || ', ' || 'ctl_act_cd=' || p_ctl_act_cd || ')');
  
  -- Be tolerant against bad initial data input: treat null as "LOGON standard", i.e. our meaningful defaults.
  if (v_ctl_act_cd is null) then
    v_ctl_act_cd := 1 /* active */;
  end if;

  ----------------------------------------------------------------------------
  -- Lookup tlgnr_sap_country_bs
  -------------------------------------------------------------------------------
  select count(bs.sap_country_cd) into v_exists_flag
    from tlgnr_sap_country_bs bs
  where bs.sap_country_cd = p_sap_country_cd;

  if (v_exists_flag > 0) then
  
    update tlgnr_sap_country_bs set
      /* sap_country_cd: cannot update because this is the key */
      ctl_act_cd                     = v_ctl_act_cd,
      ctl_mod_uid                    = 1,
      ctl_mod_ts                     = systimestamp
    where
      sap_country_cd = p_sap_country_cd and
      1 = is_different_number   (ctl_act_cd, v_ctl_act_cd)
    ;
    dbms_output.put_line ('UPDATED if needed: ' || SQL%ROWCOUNT ||'. Existing tlgnr_sap_country_bs (CD=' || p_sap_country_cd || ').');
  
  else
    insert into tlgnr_sap_country_bs (
      sap_country_cd,
      ctl_act_cd,
      ctl_cre_uid, ctl_cre_ts, ctl_mod_uid, ctl_mod_ts
    ) values (
      p_sap_country_cd,
      v_ctl_act_cd,
      1, systimestamp, 1, systimestamp
    );
    dbms_output.put_line ('INSERTED ' || SQL%ROWCOUNT ||' tlgnr_sap_country_bs (CD=' || p_sap_country_cd || ').');
  end if;

end upsert_sap_country_bs;
/
show errors;

-------------------------------------------------------------------------------
-- tlgnr_sap_country_tx
-------------------------------------------------------------------------------
create or replace
procedure upsert_sap_country_tx (
    p_sap_country_cd          in varchar2,
    p_lang_cd                 in varchar2,
    p_text                    in varchar2

) is
    v_exists_flag                   number;        -- number of existing records of that key (0 or 1)
    v_exists_bs_flag                number;        -- number of existing BASE records

begin
  dbms_output.enable(100000);

  dbms_output.put_line('Insert or Update tlgnr_sap_country_tx with (' || p_sap_country_cd || ', ' || p_lang_cd || ', ''' || p_text || ''')');

----------------------------------------------------------------------------
-- Lookup tlgnr_sap_country_bs entry first
-------------------------------------------------------------------------------
  select count(bs.sap_country_cd) into v_exists_bs_flag
    from tlgnr_sap_country_bs bs
  where bs.sap_country_cd = p_sap_country_cd;

  if (v_exists_bs_flag > 0) then
    ----------------------------------------------------------------------------
    -- Lookup tlgnr_sap_country_tx
    ----------------------------------------------------------------------------
    select count(tx.sap_country_cd) into v_exists_flag
      from tlgnr_sap_country_tx tx
    where tx.sap_country_cd = p_sap_country_cd and tx.lang_cd = p_lang_cd;

    if (v_exists_flag > 0) then
      update tlgnr_sap_country_tx set
        /* sap_country_cd and lang_cd: cannot update because these are the keys */
        txt                            = p_text,
        ctl_mod_uid                    = 1,
        ctl_mod_ts                     = systimestamp
      where
        sap_country_cd = p_sap_country_cd and
        lang_cd = p_lang_cd               and
        1 = is_different_varchar2(txt, p_text)
      ;
      dbms_output.put_line ('UPDATED if needed: ' || SQL%ROWCOUNT ||'. Existing tlgnr_sap_country_tx (CD=' || p_sap_country_cd || ', LANG=' || p_lang_cd || ').');

    else
      insert into tlgnr_sap_country_tx (
        sap_country_cd,
        lang_cd,
        txt,
        ctl_cre_uid, ctl_cre_ts, ctl_mod_uid, ctl_mod_ts
      ) values (
        p_sap_country_cd,
        p_lang_cd,
        p_text,
        1, systimestamp, 1, systimestamp
      );
      dbms_output.put_line ('INSERTED ' || SQL%ROWCOUNT ||' tlgnr_sap_country_tx (CD=' || p_sap_country_cd || ', LANG=' || p_lang_cd || ').');
    end if;
  else
    dbms_output.put_line ('ERROR: Missing entry in tlgnr_sap_country_bs (CD=' || p_sap_country_cd || ').');
  end if;

end upsert_sap_country_tx;
/
show errors;

