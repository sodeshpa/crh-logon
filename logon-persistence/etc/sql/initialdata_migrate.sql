-- Helper procedure to update sequences
-------------------------------------------------------------------------------
create or replace
procedure create_sequence_rename (p_from_sequence_name varchar2, p_to_sequence_name varchar2) IS

  l_min_value number := 0;
  sql_statement varchar2(2000);

begin
  dbms_output.enable(100000);
  
  -- sys.dba_sequences must be granted to this user (ulgn01) earlier:
  --   grant select on sys.dba_sequences to ulgn01;
  select (last_number + 1)
  into l_min_value
  from sys.dba_sequences
  where sequence_owner = 'ULGNMIG'
  and sequence_name = p_from_sequence_name;
  
  -- drop old sequence (generated by objs.sql, i.e. default values 1000 etc.)
  -- This always works for ulgn01, because owner seems to have 'drop' grants implicitely
  sql_statement := 'DROP SEQUENCE ' || p_to_sequence_name;
  dbms_output.put_line ('INFO: ' || sql_statement);
  
  execute immediate sql_statement;
  
  -- create new with updated start value
  -- When inside a procedure, rights which are granted to a role are not active.
  -- Therefore, this must be given to the user directly earlier as well:
  --   grant create sequence to ulgn01;
  sql_statement := 'CREATE SEQUENCE ulgn01.' || p_to_sequence_name || ' START WITH ' || l_min_value || ' MAXVALUE 88888888888';
  dbms_output.put_line ('INFO: ' || sql_statement);
  execute immediate sql_statement;
  
  -- Do not forget to revoke those explicit grants at the end of the whole migration again:
  --   revoke select on sys.dba_sequences from ulgn01;
  --   revoke create sequence from ulgn01;
end;
/
show errors;

-- Most have not been renamed though...
create or replace procedure create_sequence (p_sequence_name varchar2) IS
begin
  create_sequence_rename (p_sequence_name, p_sequence_name);
end;
/
show errors;

