		on (ext_order.loaded_and_delivered_uom_cd = delivered_uom_tx.uom_cd and delivered_uom_tx.lang_cd = order_status_tx.lang_cd)
	join tlgnc_ext_material ext_material
		on (ext_order.ext_material_id = ext_material.ext_material_id)
	left join tlgnc_carrier carrier
		on (ext_order.carrier_id = carrier.carrier_id)
	join tlgns_sap_vendor sap_vendor
		on (sap_vendor.sap_vendor_id = carrier.sap_vendor_id )
	join tlgnc_ext_site shipto_ext_site
		on (ext_order.unloading_ext_site_id = shipto_ext_site.ext_site_id)
where order_status_tx.lang_cd = 'en'
order by o_order_number;


COMMENT ON TABLE VLGNC_REP_EXTERNAL_ORDER IS 'View for report external orders';

REM END VLGNC_REP_EXTERNAL_ORDER

