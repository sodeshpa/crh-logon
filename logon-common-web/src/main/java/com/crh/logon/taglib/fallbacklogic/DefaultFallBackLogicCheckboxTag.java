package com.crh.logon.taglib.fallbacklogic;

import java.io.IOException;

import javax.servlet.jsp.JspException;
import javax.servlet.jsp.JspWriter;
import javax.servlet.jsp.tagext.Tag;
import javax.servlet.jsp.tagext.TagSupport;

import ch.nevis.jcan.log.JcanLogger;
import ch.nevis.jcan.log.JcanLoggerFactory;

import com.crh.logon.utils.StringUtils;
import com.crh.logon.utils.ExceptionUtil;

/**
 * Only usable INSIDE a DefaultFallBackLogicTag. The values are retrieved from there, this tag
 * renders only the checkbox according to the values stored in the DefaultFallBackLogicTag.
 * 
 * The tag renders the javacript for the checkbox, which updates the input field generated by  the
 * DefaultFallBackLogicInputFieldTag (disabled/enabled, plus sets its value).
 * 
 * @author AdNovum Informatik AG
 */
public class DefaultFallBackLogicCheckboxTag extends TagSupport { 

	private static final String C_NAME = 
		DefaultFallBackLogicCheckboxTag.class.getName();

	private static final JcanLogger LOG = JcanLoggerFactory.getLogger(C_NAME);
	
	private String style;
	private String styleClass;
	
	private boolean checked;

	public static final String PROPERTY_DEFAULT_SHIPTO_UNLOADING_TIME_MIN = "shiptoUnloading";
	public static final String PROPERTY_DEFAULT_SILO_UNLOADING_TIME_MIN = "siloUnloading";
	public static final String PROPERTY_DEFAULT_LOADINGPOINT_LOADING_TIME_MIN = "loadingPointLoading";
	
	
	public int doStartTag() throws JspException {
		// [[
		int result = 0;
		boolean logDebugEnabled = LOG.isDebugEnabled();
		if (logDebugEnabled) {
			LOG.entering(this, "doStartTag");
		}
		// ]]
		try {
			Tag tagNotCasted = findAncestorWithClass(this, DefaultFallBackLogicTag.class);
			DefaultFallBackLogicTag tag = (DefaultFallBackLogicTag) tagNotCasted;
			boolean checkCheckbox = isChecked() || tag.isChangeDisabled();
			String checkboxString = "";
			if (!tag.isReadOnly()){
				String value = tag.getFirstAvailableDefaultValue() != null ? tag.getFirstAvailableDefaultValue().toString() : "";
				checkboxString = "<input id=\"" + tag.getPropertyCheckboxName() + "\" name=\"" + tag.getPropertyCheckboxName() + "\" value=\"1\" type=\"checkbox\" onclick=\'" + 
				"Ext.getDom(\"" + tag.getPropertyInputFieldName() + "\").disabled = false;" +
				"Ext.getDom(\"" +tag.getPropertyInputFieldName() + "\").value= \"" + value + "\";" +
				"if (this.checked == true) {Ext.getDom(\"" + tag.getPropertyInputFieldName() + "\").disabled = true;}\' " + (checkCheckbox ? "checked" : "" ) + 
				(StringUtils.notEmpty(style) ? " style=\"" + style + "\" " : "" )+
				(StringUtils.notEmpty(styleClass) ? " class=\"" + styleClass + "\" " : "" )+
				"/>";				
			}
			else{
				checkboxString = "<input type = \"checkbox\" disabled " + (checkCheckbox ? "checked" : "" ) + "/>";				
			}
			JspWriter out = pageContext.getOut();				
			out.write(checkboxString);
		}
		
		catch (IOException e) {
			ExceptionUtil.errException(LOG, e, null);
		}
		finally {
		// [[
			if (logDebugEnabled) {
				LOG.exiting(result);
			}
		// ]]
		}
		return result = EVAL_BODY_INCLUDE;
	}

	public String getStyle() {
		return style;
	}

	public void setStyle(String style) {
		this.style = style;
	}

	public String getStyleClass() {
		return styleClass;
	}

	public void setStyleClass(String styleClass) {
		this.styleClass = styleClass;
	}

	public boolean isChecked() {
		return checked;
	}

	public void setChecked(boolean checked) {
		this.checked = checked;
	}
}
