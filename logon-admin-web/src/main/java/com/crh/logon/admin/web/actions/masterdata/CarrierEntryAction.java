package com.crh.logon.admin.web.actions.masterdata;

import java.io.IOException;

import javax.servlet.ServletException;
import javax.servlet.http.HttpServletRequest;
import javax.servlet.http.HttpServletResponse;

import org.apache.struts.action.ActionForm;
import org.apache.struts.action.ActionForward;
import org.apache.struts.action.ActionMapping;

import ch.nevis.jcan.log.JcanLogger;
import ch.nevis.jcan.log.JcanLoggerFactory;

import com.crh.logon.admin.web.actions.AdminActionSupport;
import com.crh.logon.admin.web.forms.masterdata.CarrierForm;
import com.crh.logon.web.utils.Authorization;

/**
 * @author      AdNovum Informatik AG
 * @version     $Revision$ $Date$
 *
 * @struts.action name="admin_CarrierForm" path="/CarrierEntry" scope="session"
 *  validate="false"
 *
 * @struts.action-forward name="success" path="CarrierTile.def"
 */
public class CarrierEntryAction extends AdminActionSupport {
	private static final JcanLogger LOG = JcanLoggerFactory.getLogger(CarrierEntryAction.class);
	
	private static final String SUCCESS_FWD = "success";
	
	public ActionForward execute(ActionMapping mapping, ActionForm form,
			HttpServletRequest request, HttpServletResponse response) throws IOException,
			ServletException {
		// [[
		ActionForward result = null;
		Object[][] params = {{"mapping", mapping},
							{"form", form},
							{"request", request},
							{"response", response}};
		boolean logDebugEnabled = LOG.isDebugEnabled();
		if (logDebugEnabled) {
			LOG.entering(this, "execute", params);
		}
		// ]]
		try {
			Authorization.authorize(Authorization.MASTER_DATA_CARRIER_VIEW);

			String forwardName = SUCCESS_FWD;
			
			// init the tabs
			setSelectedTab("masterdata", request);
			setSelectedSub1Tab("commcarrier", request);
			
			CarrierForm helpForm;
			helpForm = (CarrierForm) form;
			
			return result = mapping.findForward(forwardName);
		}
		finally {
		// [[
			if (logDebugEnabled) {
				LOG.exiting(result);
			}
		// ]]
		}
	}
}
