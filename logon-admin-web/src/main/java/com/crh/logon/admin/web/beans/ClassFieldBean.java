package com.crh.logon.admin.web.beans;

import java.io.Serializable;

import ch.nevis.jcan.log.JcanLogger;
import ch.nevis.jcan.log.JcanLoggerFactory;

/**
 * @author AdNovum Informatik AG
 */
public class ClassFieldBean implements Serializable {

	private static final long serialVersionUID = 1L;
	private static final JcanLogger LOG = JcanLoggerFactory.getLogger(ClassFieldBean.class);
	private Class type;
	private String name;
	private boolean assignable;
	private boolean bean;
	private int length = 1;
	
	public ClassFieldBean(Class type, String name) {
				
		this.name = name;
		this.type = type;
	}
	
	public Class getType() {
		return type;
	}

	public void setType(Class type) {
		this.type = type;
	}

	public String getName() {
		return name;
	}

	public void setName(String name) {
		this.name = name;
	}

	public boolean isAssignable() {
		return assignable;
	}

	public void setAssignable(boolean assignable) {
		this.assignable = assignable;
	}
	
	public int getLength() {
		return length;
	}

	public void setLength(int length) {
		this.length = length;
	}
	
	public boolean isBean() {
		return bean;
	}

	public void setBean(boolean bean) {
		this.bean = bean;
	}

	/* (non-Javadoc)
	 * @see java.lang.Object#hashCode()
	 */
	@Override
	public int hashCode() {
		/* We use the hashCode() method generated by Eclipse, with one difference:
		 * Because type is of class Class, which does not implement hashCode, we use the canonical
		 * class name here for the comparison.
		 */
		final int prime = 31;
		final String typeName = (type == null) ? null : type.getCanonicalName();
		int result = 1;
		result = prime * result + ((name == null) ? 0 : name.hashCode());
		result = prime * result + ((typeName == null) ? 0 : typeName.hashCode());
		return result;
	}

	/* (non-Javadoc)
	 * @see java.lang.Object#equals(java.lang.Object)
	 */
	@Override
	public boolean equals(Object obj) {
		if (this == obj)
			return true;
		if (obj == null)
			return false;
		if (!(obj instanceof ClassFieldBean))
			return false;
		ClassFieldBean other = (ClassFieldBean) obj;
		if (name == null) {
			if (other.name != null)
				return false;
		}
		else if (!name.equals(other.name))
			return false;
		if (type == null) {
			if (other.type != null)
				return false;
		}
		else if (!type.equals(other.type))
			return false;
		return true;
	}
}
